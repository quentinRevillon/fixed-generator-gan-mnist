def examples():
    run = lambda name, f='G.pth': load(Generator(), REPO / 'runs' / name / f)
    clf = from_main(Classifier(), 'checkpoints/mnist_classifier.pth')
    z = torch.randn(100, 100, generator=torch.Generator().manual_seed(0))

    # 1. Same latent vectors through every configuration of the common protocol.
    panels = [('(a) Baseline', run('cmploc_baseline_s1')),
              ('(b) RpGAN + R1, raw $G$', run('cmploc_rpgan_r1_ema_s1', 'G_raw.pth')),
              ('(c) RpGAN + R1 + EMA', run('cmploc_rpgan_r1_ema_s1')),
              ('(d) + noise 0.3', run('cmploc_rpgan_r1_ema_noise_03_s1'))]
    fig, axes = plt.subplots(1, 4, figsize=(7.0, 2.0), gridspec_kw={'wspace': 0.06})
    for ax, (title, G) in zip(axes, panels):
        ax.imshow(mosaic(gen(G, z), 10, 10), cmap='gray', vmin=0, vmax=1)
        ax.set_title(title)
        ax.axis('off')
    fig.subplots_adjust(left=0.005, right=0.995, top=0.9, bottom=0.01)
    fig.savefig(FIGS / 'examples_same_z.pdf', dpi=300)
    plt.close(fig)

    # 2. The 100-epoch loss campaign (seed 0), same z: collapse, divergence, gamma.
    panels = [('(a) Baseline, collapsed', run('ema100_baseline_s2', 'G_raw.pth')),
              ('(b) $\\gamma=0.1$, diverged', run('ema100_rpgan_r1_g0.1_s0', 'G_raw.pth')),
              ('(c) $\\gamma=10$', run('ema100_rpgan_r1_g10_s0')),
              ('(d) R3GAN, $\\gamma=1$', run('ema100_r3gan_s0'))]
    fig, axes = plt.subplots(1, 4, figsize=(7.0, 2.0), gridspec_kw={'wspace': 0.06})
    for ax, (title, G) in zip(axes, panels):
        ax.imshow(mosaic(gen(G, z[:64]), 8, 8), cmap='gray', vmin=0, vmax=1)
        ax.set_title(title)
        ax.axis('off')
    fig.subplots_adjust(left=0.005, right=0.995, top=0.88, bottom=0.01)
    fig.savefig(FIGS / 'examples_campaign.pdf', dpi=300)
    plt.close(fig)

    # 3. Images sorted by the digit the classifier predicts (first 12 of each digit among 10,000 samples).
    big = torch.randn(10_000, 100, generator=torch.Generator().manual_seed(1))
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.3))
    counts = {}
    for ax, (title, G) in zip(axes, [('Baseline', run('cmploc_baseline_s1')),
                                     ('RpGAN + R1 + EMA', run('cmploc_rpgan_r1_ema_s1'))]):
        x = gen(G, big)
        y = predict(clf, x)
        counts[title] = torch.bincount(y, minlength=10).tolist()
        rows = []
        for d in range(10):
            xd = x[y == d][:12]
            rows.append(torch.cat([xd, torch.zeros(12 - len(xd), 1, 28, 28)]) if len(xd) < 12 else xd)
        ax.imshow(mosaic(torch.cat(rows), 10, 12), cmap='gray', vmin=0, vmax=1)
        ax.set_title(title)
        ax.set_yticks([14.5 + 29 * d for d in range(10)])
        ax.set_yticklabels([f'{d}  ({counts[title][d] / 100:.1f}%)' for d in range(10)])
        ax.set_xticks([])
        for s in ax.spines.values():
            s.set_visible(False)
        ax.tick_params(length=0)
    fig.tight_layout(pad=0.3)
    fig.savefig(FIGS / 'examples_by_digit.pdf', dpi=300)
    plt.close(fig)

    # 4. Submitted model: OBRS (K = 3) with the recalibrated D of checkpoints/ on main.
    G, D = from_main(Generator(), 'checkpoints/G.pth'), from_main(Discriminator(), 'checkpoints/D.pth')
    zp = torch.randn(50_000, 100, generator=torch.Generator().manual_seed(2))
    with torch.no_grad():
        xs = G(zp)
        log_r = D.logit(xs).double()
    lo, hi = log_r.min().item(), log_r.max().item() + np.log(3)
    for _ in range(100):  # tau_K such that mean(min(1, exp(log_r - tau))) = 1/K (sampling.py)
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if torch.exp((log_r - mid).clamp(max=0)).mean().item() > 1 / 3 else (lo, mid)
    tau = min((lo + hi) / 2, log_r.max().item())
    a = torch.exp((log_r - tau).clamp(max=0)).float()
    x = ((xs + 1) / 2).clamp(0, 1).view(-1, 1, 28, 28)
    y = predict(clf, x)
    order = torch.argsort(a)
    fig = plt.figure(figsize=(7.0, 2.35))
    gs = fig.add_gridspec(1, 3, width_ratios=[1, 1, 1.25])
    for k, (title, idx) in enumerate([(f'(a) lowest acceptance ($a\\leq${a[order[47]]:.3f})', order[:48]),
                                      ('(b) accepted surely ($a=1$)', order[-48:])]):
        ax = fig.add_subplot(gs[k])
        ax.imshow(mosaic(x[idx], 6, 8), cmap='gray', vmin=0, vmax=1)
        ax.set_title(title)
        ax.axis('off')
    ax = fig.add_subplot(gs[2])
    acc = [a[y == d].mean().item() for d in range(10)]
    ax.bar(range(10), acc, color=C_RP)
    ax.axhline(1 / 3, color='k', ls=':', lw=0.8)
    ax.set_xticks(range(10))
    ax.set_xlabel('digit predicted by the classifier')
    ax.set_ylabel('mean acceptance probability')
    ax.set_title('(c) acceptance by digit (dotted: $1/K$)')
    fig.tight_layout(pad=0.3)
    fig.savefig(FIGS / 'obrs_kept_rejected.pdf', dpi=300)
    plt.close(fig)
    print(f'OBRS: tau={tau:.3f}, a=1 for {(a >= 1).float().mean():.1%}, mean a={a.mean():.3f}, '
          f'acceptance by digit {[round(v, 2) for v in acc]}; digit counts {counts}')
    return acc, (a >= 1).float().mean().item()


