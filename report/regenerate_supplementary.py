def per_seed_body(groups, n_seeds, extra=('precision', 'recall', 'fid_cnn', 'acceptance_rate')):
    body = ''
    for label, rows in groups:
        by_seed = {int(re.search(r'_s(\d)', r['run']).group(1)): r for r in rows}
        cells = []
        for s in range(n_seeds):
            r = by_seed.get(s)
            cells.append('' if r is None else (fmt(float(r['fid'])) if healthy(r) else
                                               f'\\textit{{c}}'))
        ok = [r for r in rows if healthy(r)]
        fid = [float(r['fid']) for r in ok]
        stats = [fmt(st.mean(float(r[k]) for r in ok), 2 if k != 'fid_cnn' else 1) if ok else '--' for k in extra]
