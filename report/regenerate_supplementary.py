def git_show(branch, path):
    return subprocess.run(['git', '-C', str(REPO), 'show', f'{branch}:{path}'], check=True,
                          capture_output=True).stdout


def csv_rows(name=None, branch=None, path=None):
    if branch:
        return list(csv.DictReader(io.StringIO(git_show(branch, path).decode())))
    with open(HERE / 'data' / f'{name}.csv', newline='') as f:
        return list(csv.DictReader(f))


def jsonl(branch, path):
    return [json.loads(line) for line in git_show(branch, path).decode().splitlines() if line.strip()]


def log_fid(branch, path):
    """(epoch, FID_CNN on val) pairs printed every 10 epochs in a training log."""
    out = []
    for line in git_show(branch, path).decode(errors='ignore').splitlines():
        m = re.match(r'\[(\d+)/\d+\].*FID=([\d.]+)', line)
        if m:
            out.append((int(m.group(1)), float(m.group(2))))
    return out


def shares(classes):
    c = np.array([int(v) for v in classes.split('-')], float)
    return c / c.sum()


healthy = lambda r: float(r['recall_cnn']) >= 0.01
fmt = lambda v, d=1: f'{v:.{d}f}'


def mean_sd(values, d=1):
    if not values:
        return '--'
    return f'{st.mean(values):.{d}f}' + (f' $\\pm$ {st.stdev(values):.{d}f}' if len(values) > 1 else '')


def write_table(name, source, body, caption, label, spec, header, size='\\footnotesize', wide=False):
    env = 'table'  # the supplementary material is set in one column
    tex = (f'% Generated by regenerate_supplementary.py from {source}\n'
           f'\\begin{{{env}}}[H]\n\\centering\n{size}\n\\setlength{{\\tabcolsep}}{{4pt}}\n'
           f'\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header} \\\\\n\\midrule\n' + body +
           f'\\bottomrule\n\\end{{tabular}}\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{{env}}}\n')
    (TABS / f'{name}.tex').write_text(tex)


# ---------------------------------------------------------------------------------------------- models
class Generator(nn.Module):  # identical to model.py
    def __init__(self):
        super().__init__()
        self.fc1, self.fc2, self.fc3, self.fc4 = (nn.Linear(100, 256), nn.Linear(256, 512),
                                                  nn.Linear(512, 1024), nn.Linear(1024, 784))

    def forward(self, x):
        for fc in (self.fc1, self.fc2, self.fc3):
            x = F.leaky_relu(fc(x), 0.2)
        return torch.tanh(self.fc4(x))


class Discriminator(nn.Module):  # identical to model.py; logit() is the pre-sigmoid score
    def __init__(self):
        super().__init__()
        self.fc1, self.fc2, self.fc3, self.fc4 = (nn.Linear(784, 1024), nn.Linear(1024, 512),
                                                  nn.Linear(512, 256), nn.Linear(256, 1))

    def logit(self, x):
        for fc in (self.fc1, self.fc2, self.fc3):
            x = F.leaky_relu(fc(x), 0.2)
        return self.fc4(x).squeeze(1)


class Classifier(nn.Module):  # evaluate.py of the repository
    def __init__(self):
        super().__init__()
        self.conv = nn.Sequential(nn.Conv2d(1, 32, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
                                  nn.Conv2d(32, 64, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2))
        self.fc = nn.Linear(64 * 7 * 7, 128)
        self.out = nn.Linear(128, 10)

    def forward(self, x):
        return self.out(F.relu(self.fc(self.conv(x).flatten(1))))


def load(model, source):
    state = torch.load(source, map_location='cpu', weights_only=False)
    model.load_state_dict({k.replace('module.', ''): v for k, v in state.items()})
    return model.eval()


def from_main(model, path):
    return load(model, io.BytesIO(git_show(MAIN, path)))


def gen(G, z):
    with torch.no_grad():
        return ((G(z) + 1) / 2).clamp(0, 1).view(-1, 1, 28, 28)


def predict(clf, x):
    with torch.no_grad():
        return clf(x).argmax(1)


def mosaic(x, rows, cols):
    x = x[:rows * cols].squeeze(1).numpy()
    img = np.ones((rows * 29 + 1, cols * 29 + 1))
    for i, im in enumerate(x):
        r, c = divmod(i, cols)
        img[1 + 29 * r:29 * (r + 1), 1 + 29 * c:29 * (c + 1)] = 1 - im
    return img


