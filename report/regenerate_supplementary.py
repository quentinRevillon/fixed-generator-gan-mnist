def plot_scores():
    files = [('Baseline', 'hist_bl_s1', C_BASE), ('RpGAN + R1, raw $G$', 'hist_rp_s1_raw', C_RAW),
             ('RpGAN + R1 + EMA', 'hist_rp_s1_ema', C_RP)]
    fig, axes = plt.subplots(1, 3, figsize=(7.0, 1.8))
    aucs = {}
    for ax, (title, name, color) in zip(axes, files):
        r = csv_rows(branch=ENQ, path=f'rapport/enquete/results/drs/{name}.csv')
        b = np.array([float(x['bin_left']) for x in r])
        real, fake = (np.array([float(x[k]) for x in r]) for k in ('real_count', 'fake_count'))
        w = b[1] - b[0]
        ax.bar(b, real / real.sum() / w, width=w, align='edge', color='#555', alpha=0.5, label='real')
        ax.bar(b, fake / fake.sum() / w, width=w, align='edge', color=color, alpha=0.6, label='generated')
        # AUC from the two histograms (ties inside a bin count one half)
        pr, pf = real / real.sum(), fake / fake.sum()
        auc = float(np.sum(pr * (np.cumsum(pf) - pf / 2)))
        aucs[title] = auc
        lo, hi = np.percentile(np.repeat(b, (real + fake).astype(int)), [0.5, 99.5])
        ax.set_xlim(lo, hi + w)
        ax.set(title=f'{title}: AUC {auc:.2f}', xlabel='score $f(x)$ of $D$ as trained')
        ax.set_yticks([])
    axes[0].legend(frameon=False, loc='upper left')
    fig.tight_layout(pad=0.3)
    fig.savefig(FIGS / 'd_scores.pdf')
    plt.close(fig)
    print('AUC from score histograms', {k: round(v, 3) for k, v in aucs.items()})


