def table_campaign():
    R = {r['run']: r for r in csv_rows(branch=TRAIN, path='results.csv')}
    logs = {}
    for name in ('ema100_rpgan_r1_g0.1_s0', 'ema100_rpgan_r1_g0.1_s1', 'ema100_rpgan_r1_g0.1_s2'):
        logs[name] = log_fid(TRAIN, f'logs/{name}.log')[-1]
    configs = [('Baseline (BCE)', 'ema100_baseline'), ('RpGAN + R1, $\\gamma=0.1$', 'ema100_rpgan_r1_g0.1'),
               ('RpGAN + R1, $\\gamma=1$', 'ema100_rpgan_r1'), ('RpGAN + R1, $\\gamma=10$', 'ema100_rpgan_r1_g10'),
               ('R3GAN (R1 + R2), $\\gamma=1$', 'ema100_r3gan')]
    body = ''
    for label, run in configs:
        cells, ok = [], []
        for s in range(3):
            r = R.get(f'{run}_s{s}')
            if r is None:
                ep, v = logs[f'{run}_s{s}']
                cells.append(f'\\textit{{d}} ({v:.0f} at ep.\\ {ep})')
            elif float(r['recall']) < 0.01:
                cells.append(f'\\textit{{c}} ({float(r["fid"]):.0f})')
            else:
                cells.append(fmt(float(r['fid'])))
                ok.append(r)
        stats = [mean_sd([float(r['fid']) for r in ok])] + [fmt(st.mean(float(r[k]) for r in ok), 2) if ok else '--'
                                                            for k in ('precision', 'recall')]
        sh = [100 * shares(r['classes']) for r in ok]
        stats.append(f'{min(min(x) for x in sh):.0f}--{max(max(x) for x in sh):.0f}' if ok else '--')
        body += ' & '.join([label] + cells + stats) + ' \\\\\n'
    body += '\\midrule\n\\multicolumn{8}{l}{\\textit{First series: 50 epochs, seed 0, no EMA}} \\\\\n'
    for label, run in (('Baseline (BCE)', 'baseline_rerun'), ('RpGAN, no penalty', 'train_rpgan'),
                       ('RpGAN + R1, $\\gamma=1$', 'train_rpgan_r1'), ('R3GAN, $\\gamma=1$', 'train_r3gan'),
                       ('R3GAN, $\\gamma=1$, Adam $\\beta=(0, 0.99)$', 'train_r3gan_adam')):
        r = R[run]
        bad = float(r['recall']) < 0.01
        sh = 100 * shares(r['classes'])
        body += ' & '.join([label, (f'\\textit{{c}} ({float(r["fid"]):.0f})' if bad else fmt(float(r['fid']))), '', '',
                            '', fmt(float(r['precision']), 2), fmt(float(r['recall']), 2),
                            f'{sh.min():.0f}--{sh.max():.0f}']) + ' \\\\\n'
    write_table('campaign', 'results.csv and logs/ of the branch noe/training', body,
                'Loss campaign (100 epochs, EMA 0.999, three seeds; scores against the 10,000 validation images, '
                'with the classifier features used during training). \\textit{c}: collapsed run; \\textit{d}: '
                'diverged run, stopped (last \\fcnn{} printed in its log). P, R: classifier precision and recall '
                '($k=3$); Digits: range of the share of each digit (\\%).', 'tab:supp-campaign', 'lrrrrrrr',
                'Configuration & s0 & s1 & s2 & \\fcnn{} & P & R & Digits (\\%)', wide=True)


