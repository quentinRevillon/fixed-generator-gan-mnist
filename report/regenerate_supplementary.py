    ep = np.array([r['epoch'] for r in rows])
    finc, fcnn = np.array([r['fid_prof'] for r in rows]), np.array([r['fid'] for r in rows])
    sh = np.array([shares('-'.join(map(str, r['classes']))) for r in rows])
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.0))
